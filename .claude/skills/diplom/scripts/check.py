def check(path):
    ps = paragraphs(path)
    hits = {n: [] for n, *_ in RULES}
    gekh = 0; pct_word = pct_sym = 0
    tables, figs = [], []
    refs_n = 0; cited = set()
    in_refs = False
    for i, p in enumerate(ps):
        if p.strip() == 'АШИГЛАСАН МАТЕРИАЛ':
            in_refs = True; continue
        if in_refs:
            if re.match(r'\[\d+\]', p): refs_n += 1
            continue
        is_eq = bool(re.match(r'^\t.*\t\(\d+(\.\d+)?\)$', p))
        for n, name, rx, cat in RULES:
            if n == 49 and is_eq: continue   # томьёоны мөр табаар эхэлдэг
            if rx is not None:
                for m in rx.finditer(p):
                    hits[n].append((i, p[max(0, m.start()-30):m.end()+30]))
        if p.count('«') != p.count('»'): hits[23].append((i, p[:80]))
        # «а) …; б) …» жагсаалтын тэмдэглэгээг хаалт гэж тоолохгүй
        pb = re.sub(r'(^|: |; )[а-яё]\)', r'\1', p)
        if pb.count('(') != pb.count(')'): hits[24].append((i, p[:80]))
        for s in re.split(r'(?<=[.!?])\s+', p):
            if len(s.split()) > 45: hits[38].append((i, s[:90] + '…'))
        if len(p.split()) > 230: hits[39].append((i, p[:80] + '…'))
        if re.search(r'\d+(\.\d+)?\s?(сая|мянган|%|км|тонн)', p) and '[' not in p and not p.startswith(('Хүснэгт', 'Зураг')) and len(p) > 120:
            hits[41].append((i, p[:90] + '…'))
        gekh += p.count('гэх мэт')
        pct_word += len(re.findall(r'\d хувь', p)); pct_sym += len(re.findall(r'\d%', p))
        m = re.match(r'Хүснэгт ([\dУ.]+)$', p.strip())
        if m: tables.append(m.group(1))
        m = re.match(r'Зураг ([\d.]+)\.', p.strip())
        if m: figs.append(m.group(1))
        for c in re.findall(r'\[(\d+(?:, \d+)*)\]', p):
            cited.update(int(x) for x in c.split(', '))
    if gekh > 6: hits[46].append((-1, f'{gekh} удаа'))
    if pct_word and pct_sym: hits[47].append((-1, f'«хувь» {pct_word}, «%» {pct_sym}'))
    for lst, n in ((tables, 42), (figs, 43)):
        if len(lst) != len(set(lst)): hits[n].append((-1, 'давхардсан: ' + ', '.join(lst)))
    if refs_n and cited and max(cited) > refs_n:
        hits[44].append((-1, f'иш татсан хамгийн их [{max(cited)}], жагсаалтад {refs_n}'))
    return hits, len(ps)

def main():
    total = 0
    for path in sys.argv[1:]:
        hits, n = check(path)
        ADV = (17, 18, 40, 41)   # зөвлөмж — гараар шалгана
        bad = {k: v for k, v in hits.items() if v and k not in ADV}
        print(f'\n=== {path}  ({n} догол мөр)')
        for num, name, rx, cat in RULES:
            v = hits[num]
            if not v: continue
            mark = 'ℹ' if num in (17, 18, 40, 41) else '✗'
            print(f'  {mark} [{num:2}] {name}: {len(v)}')
            for i, s in v[:4]:
                print(f'        ¶{i}: {s}')
        print(f'  ✓ {50 - len(bad)}/50 шалгуур цэвэр' + (f'; нягтлах тэмдэглэгээ {len(hits[40])}' if hits[40] else ''))
        total += len(bad)
    sys.exit(0)

if __name__ == '__main__':
    main()
