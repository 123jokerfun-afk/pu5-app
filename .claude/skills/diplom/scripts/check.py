# Хэрэглээ: python3 check.py файл1.docx [файл2.docx ...]
import re, sys, zipfile

def paragraphs(path):
    xml = zipfile.ZipFile(path).read('word/document.xml').decode('utf8')
    out = []
    for m in re.finditer(r'<w:p[ >].*?</w:p>', xml, re.S):
        # Томьёоны доод/дээд индексийг (Nт, м²) үгэнд наалдсан латин үсэг
        # гэж буруу барихгүйн тулд үл харагдах тэмдгээр тусгаарлана
        parts = []
        for r in re.finditer(r'<w:r[ >].*?</w:r>', m.group(0), re.S):
            x = ''.join(re.findall(r'<w:t(?: [^>]*)?>([^<]*)</w:t>', r.group(0)))
            if 'w:vertAlign' in r.group(0) and x:
                x = '\u200b' + x + '\u200b'
            parts.append(x)
        t = ''.join(parts)
        t = t.replace('&amp;', '&').replace('&lt;', '<').replace('&gt;', '>')
        if t.strip():
            out.append(t)
    return out

